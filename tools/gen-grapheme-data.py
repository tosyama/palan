import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "src/std/graphemeprops.pa"
TEST = ROOT / "test/testdata/std/GraphemeBreakTest.txt"

# Enumerator order is the value packed into the table's low 4 bits.
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
       "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Linker", "Consonant", "Extend"]
EXT_PICT = 1 << 4
INCB_SHIFT = 5


def enum_name(v):
    return {"SpacingMark": "SPACING_MARK"}.get(v, v.upper())


def fetch(base, path, version_line):
    text = urllib.request.urlopen(base + path).read().decode("utf-8")
    if version_line not in text.split("\n", 20)[:20]:
        sys.exit(f"{path}: not version {version_line!r}")
    return text


def records(text):
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if line:
            fields = [f.strip() for f in line.split(";")]
            first, _, last = fields[0].partition("..")
            yield int(first, 16), int(last or first, 16), fields[1:]


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen-grapheme-data.py <unicode-version>")
    ver = sys.argv[1]
    base = f"https://www.unicode.org/Public/{ver}/ucd/"
    gbp = fetch(base, "auxiliary/GraphemeBreakProperty.txt", f"# GraphemeBreakProperty-{ver}.txt")
    emoji = fetch(base, "emoji/emoji-data.txt", f"# Version: {ver}")
    dcp = fetch(base, "DerivedCoreProperties.txt", f"# DerivedCoreProperties-{ver}.txt")
    test = fetch(base, "auxiliary/GraphemeBreakTest.txt", f"# GraphemeBreakTest-{ver}.txt")

    props = [0] * 0x110000
    for a, b, f in records(gbp):
        if f[0] not in GCB:
            sys.exit(f"unknown Grapheme_Cluster_Break value {f[0]}")
        for c in range(a, b + 1):
            props[c] |= GCB.index(f[0])
    for a, b, f in records(emoji):
        if f[0] == "Extended_Pictographic":
            for c in range(a, b + 1):
                props[c] |= EXT_PICT
    for a, b, f in records(dcp):
        if f[0] == "InCB":
            if f[1] not in INCB:
                sys.exit(f"unknown InCB value {f[1]}")
            for c in range(a, b + 1):
                props[c] |= INCB.index(f[1]) << INCB_SHIFT

    starts = [c for c in range(0x110000) if c == 0 or props[c] != props[c - 1]]

    # Checks at each end of the first run of every value of each property, and just outside it.
    points = {0, 0x10FFFF}
    for mask in (0x0F, EXT_PICT, 3 << INCB_SHIFT):
        seen = set()
        for i, s in enumerate(starts):
            v = props[s] & mask
            if v in seen:
                continue
            seen.add(v)
            j = i + 1
            while j < len(starts) and props[starts[j]] & mask == v:
                j += 1
            end = (starts[j] if j < len(starts) else 0x110000) - 1
            points |= {c for c in (s - 1, s, end, end + 1) if 0 <= c <= 0x10FFFF}

    out = [
        "library std;",
        "",
        "// Generated by tools/gen-grapheme-data.py " + ver + "; do not edit.",
        f"// From the Unicode Character Database {ver} (https://www.unicode.org/Public/{ver}/ucd/):",
        "// GraphemeBreakProperty.txt, emoji-data.txt (Extended_Pictographic) and",
        "// DerivedCoreProperties.txt (InCB). Copyright (c) Unicode, Inc., distributed under the",
        "// Unicode License v3 (LICENSE-Unicode.txt).",
        "",
        "cinclude <stdio.h>;",
        "cinclude <stdlib.h>;",
        "",
        "export type gcbProp enum {",
        ",\n".join("\t" + enum_name(v) for v in GCB),
        "};",
        "",
        "export type incbProp enum {",
        ",\n".join("\t" + enum_name(v) for v in INCB),
        "};",
        "",
        "// Each range runs from its start to the next one's; its properties are packed as gcbProp in",
        f"// the low 4 bits, Extended_Pictographic in bit 4 and incbProp from bit {INCB_SHIFT}.",
        f"global $[{len(starts)}]int32 starts = [",
    ]
    out += rows([str(s) for s in starts], 12)
    out += ["] for graphemeProps;", f"global $[{len(starts)}]uint8 props = ["]
    out += rows([str(props[s]) for s in starts], 20)
    out += [
        "] for graphemeProps;",
        "",
        "export func graphemeProps(int32 c) -> uint8",
        "{",
        f"\tint64 lo = 0, hi = {len(starts)};",
        "\twhile hi - lo > 1 {",
        "\t\tint64 mid = (lo + hi) / 2;",
        "\t\tif starts[mid] <= c { mid -> lo; } else { mid -> hi; }",
        "\t}",
        "\treturn props[lo];",
        "}",
        "",
        "export func gcbOf(uint8 p) -> gcbProp { return gcbProp(p & 15); }",
        f"export func isExtPict(uint8 p) -> bool {{ return (p & {EXT_PICT}) != 0; }}",
        f"export func incbOf(uint8 p) -> incbProp {{ return incbProp(p >>> {INCB_SHIFT}); }}",
        "",
        "func check(int32 c, uint8 p)",
        "{",
        "\tif graphemeProps(c) != p {",
        "\t\tprintf(\"graphemeProps(0x%X) is 0x%02X, not 0x%02X\\n\", c, graphemeProps(c), p);",
        "\t\texit(1);",
        "\t}",
        "}",
        "",
    ]
    out += [f"check({c}, {props[c]});" for c in sorted(points)]

    TABLE.write_text("\n".join(out) + "\n")
    TEST.parent.mkdir(parents=True, exist_ok=True)
    TEST.write_text(test)
    print(f"{TABLE.relative_to(ROOT)}: {len(starts)} ranges, {len(points)} checks")


def rows(items, n):
    return ["\t" + ", ".join(items[i:i + n]) + ("," if i + n < len(items) else "")
            for i in range(0, len(items), n)]


if __name__ == "__main__":
    main()
